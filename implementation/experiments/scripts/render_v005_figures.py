OUT_FIG = REPO_ROOT / "figures"
OUT_TEX = REPO_ROOT / "chapters" / "results" / "_generated_figures.tex"
HEADER = ["% GENERATED by implementation/experiments/scripts/render_v005_figures.py.",
          "% Do not edit by hand -- regenerate from results/runs/<root>/ instead.", ""]
NAMES = rt.NAMES
SHORT = dict(rt.SHORT, nas_bench_201_v005="NB201")
SLOTS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]
MARKERS = ["o", "s", "^", "D", "v"]
GREY, INK, INK2 = "#c3c2b7", "#2f2f2d", "#6b6a63"
CRC = "jahs_bench_201_colorectal_v005"


def _style(ax):
    ax.tick_params(labelsize=6)
    ax.grid(alpha=0.25, lw=0.4)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)


def _save(fig, stem: str) -> list[Path]:
    OUT_FIG.mkdir(parents=True, exist_ok=True)
    out = [OUT_FIG / f"{stem}.pdf", OUT_FIG / f"{stem}.png"]
    for p in out:
        fig.savefig(p, dpi=200)
    return out


# ------------------------------------------------------------------------------------------- 1. rank by budget

def rank_by_budget(med: pd.DataFrame, plt) -> list[Path]:
    groups = [("Primary spaces", rt.PRIMARY),
              ("FCNet and NAS-Bench-201", [*rt.FCNET, "nas_bench_201_v005"])]
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.3), constrained_layout=True, sharey=True)
    for ax, (title, spaces) in zip(axes, groups):
        ends = []
        for i, s in enumerate(spaces):
            c = med[(med.space == s) & (med.method == spec.REF)].sort_values("budget")
            rel = (c["rank"] - 1) / (c["n_arms"] - 1)
            ax.plot(c.budget, rel, color=SLOTS[i], marker=MARKERS[i], ms=4, lw=1.4)
            ends.append([float(rel.iloc[-1]), SHORT[s], float(c.budget.iloc[-1])])
        ends.sort()
        for k in range(1, len(ends)):  # push labels apart by at least 0.06 on the rank axis
            ends[k][0] = max(ends[k][0], ends[k - 1][0] + 0.06)
        for y, name, x in ends:
            ax.annotate(name, (x, y), xytext=(6, 0), textcoords="offset points", fontsize=6, color=INK,
                        va="center")
        ax.set_xticks(list(spec.BUDGETS))
        ax.set_xlim(30, 430)
        ax.set_xlabel("budget (full evaluations)", fontsize=7)
        ax.set_title(title, fontsize=7)
        _style(ax)
    axes[0].set_ylim(1.03, -0.03)  # best at the top
    axes[0].set_ylabel("P3Net's relative rank\n(0 = best arm, 1 = worst)", fontsize=7)
    out = _save(fig, "rank__p3net__by_budget")
    plt.close(fig)
    return out


# ------------------------------------------------------------------------------------------- 2. quality vs cost

def quality_vs_cost(med: pd.DataFrame, costs: pd.DataFrame, plt) -> list[Path]:
    labelled = {spec.REF: SLOTS[0], "v005_p3_canonical": SLOTS[1], "v005_random_search": SLOTS[2]}
    named = {"v005_vizier", "v005_nsganetv2", "v005_qnehvi"}
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.4), constrained_layout=True)
    for ax, b in zip(axes, (100, max(spec.BUDGETS))):
        q = med[(med.space == CRC) & (med.budget == b)].set_index("method").value
        t = costs[(costs.space == CRC) & (costs.budget == b)].set_index("method").method_wall_seconds
        arms = [a for a in MAIN_ARMS if a in q.index and a in t.index]
        for a in arms:
            x, y = max(t[a], 1e-2), q[a]
            if a in labelled:
                ax.scatter(x, y, s=28, color=labelled[a], edgecolor="white", lw=0.8, zorder=3)
            else:
                ax.scatter(x, y, s=14, color=GREY, zorder=2)
            if a in labelled or a in named:
                dy = {"v005_p3_canonical": -9, spec.REF: 3}.get(a, 2)
                ax.annotate(NAMES[a], (x, y), xytext=(4, dy), textcoords="offset points", fontsize=5.5,
                            color=INK if a in labelled else INK2)
        ax.set_xscale("log")
        ax.set_xlabel("median optimiser time per run (s, log scale)", fontsize=7)
        ax.set_title(f"JAHS-Bench-201 CRC, $b = {b}$", fontsize=7)
        _style(ax)
    axes[0].set_ylabel("median HV (higher is better)", fontsize=7)
    out = _save(fig, "quality_vs_cost__colorectal")
    plt.close(fig)
    return out


# ------------------------------------------------------------------------------------------- 3. fronts

def _front(points: list[tuple[float, float]]) -> np.ndarray:
    pts = sorted(set(points))
    out, best2 = [], float("inf")
    for f1, f2 in pts:  # sorted by f1 then f2: keep a point iff it lowers the best f2 so far
        if f2 < best2:
            out.append((f1, f2))
            best2 = f2
    return np.array(out)


def median_run(per_run: pd.DataFrame, method: str, space: str, budget: int) -> int:
    """Seed of the median run: index (n - 1) // 2 after sorting by the primary metric (better first), then seed
    (the rule of pre-registration §8.4)."""
    c = per_run[(per_run.method == method) & (per_run.space == space) & (per_run.budget == budget)]
    hv = spec.SPACES[space][1] == "hv"
    c = c.sort_values(["value", "seed"], ascending=[not hv, True])
    return int(c.seed.iloc[(len(c) - 1) // 2])


def fronts(root: Path, per_run: pd.DataFrame, med: pd.DataFrame, plt) -> tuple[list[Path], str]:
    b = max(spec.BUDGETS)
    cell = med[(med.space == CRC) & (med.budget == b)]
    best = cell.sort_values("value", ascending=False).method.iloc[0]
    arms = [(spec.REF, SLOTS[0], "-", "o"), (best, INK, "-.", "s"), ("v005_random_search", SLOTS[2], ":", "^")]
    fig, ax = plt.subplots(figsize=(3.4, 2.5), constrained_layout=True)
    for m, col, ls, mk in arms:
        seed = median_run(per_run, m, CRC, b)
        rec = json.loads((root / "raw" / f"{m}__{CRC}__budget{b}__seed{seed}.json").read_text(encoding="utf-8"))
        f = _front([(h["objectives"][0], h["objectives"][1] / 1e6) for h in rec["history"]])
        ax.step(f[:, 1], f[:, 0], where="post", color=col, ls=ls, lw=1.3)
        ax.scatter(f[:, 1], f[:, 0], s=10, color=col, marker=mk, zorder=3,
                   label=f"{NAMES[m]}" + (" (best median HV)" if m == best else "") + f", seed {seed}")
    ax.set_xlabel("$f_2$: parameters (millions)", fontsize=7)
    ax.set_ylabel("$f_1$: validation error (%)", fontsize=7)
    ax.legend(fontsize=5.5, frameon=False, loc="upper right")
    _style(ax)
    out = _save(fig, "fronts__colorectal__budget350")
    plt.close(fig)
    return out, best


def tex(best: str) -> str:
    return "\n".join(HEADER + [
        "\\begin{figure*}[t]", "    \\centering",
        "    \\includegraphics[width=\\textwidth]{figures/rank__p3net__by_budget.pdf}",
        "    \\caption{P3Net's standing by budget: relative rank of its median final quality among the main-track arms "
        "run in the cell (0 = best, 1 = worst; 22 arms at $b \\le 100$, 19 at $b \\ge 200$, ties share the lower rank). "
        "Left: the primary spaces; right: the FCNet tasks and NAS-Bench-201.}",
        "    \\Description{Two line charts of P3Net's relative rank against the budget, one line per search space: on "
        "most spaces the rank improves from near the worst at 50 evaluations to near the best at 200 or 350.}",
        "    \\label{fig:v005-rank-budget}", "\\end{figure*}", "",
        "\\begin{figure*}[t]", "    \\centering",
        "    \\includegraphics[width=\\textwidth]{figures/quality_vs_cost__colorectal.pdf}",
        "    \\caption{Quality against the optimiser's own cost on JAHS-Bench-201 Colorectal Histology: median HV over 30 "
        "seeds and median optimiser wall-clock time per run without benchmark queries (log scale), one point per "
        "main-track arm, at $b = 100$ (with the Gaussian-process arms) and $b = 350$; times below 0.01\\,s are drawn at "
        "0.01\\,s. Coloured: P3Net, canonical P3 and random search; grey: the other arms.}",
        "    \\Description{Two scatter plots of median hypervolume against optimiser time on a log axis; the "
        "Gaussian-process arms and NSGANetV2 are the most expensive, P3Net and canonical P3 among the cheapest.}",
        "    \\label{fig:v005-quality-cost}", "\\end{figure*}", "",
        "\\begin{figure}[t]", "    \\centering",
        "    \\includegraphics[width=\\linewidth]{figures/fronts__colorectal__budget350.pdf}",
        "    \\caption{Final non-dominated fronts of the median run (by HV) of P3Net, of the arm with the best median HV "
        f"({NAMES[best]}) and of random search, JAHS-Bench-201 Colorectal Histology, $b = 350$; both objectives are "
        "minimised.}",
        "    \\Description{Step plots of validation error against parameter count for three fronts; the fronts of "
        "P3Net and of the best arm both reach about four percent error, random search's front stays higher.}",
        "    \\label{fig:v005-fronts}", "\\end{figure}", ""])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", type=Path, help="results/runs/<root> (with analysis/ and raw/)")
    args = ap.parse_args(argv)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    a = args.root / "analysis"
    per_run = pd.read_csv(a / "per_run.csv", usecols=["method", "space", "budget", "seed", "value", "stop_reason"])
    med = cell_medians(per_run)
    costs = pd.read_csv(a / "costs.csv")
    paths = rank_by_budget(med, plt) + quality_vs_cost(med, costs, plt)
    p3, best = fronts(args.root, per_run, med, plt)
    OUT_TEX.write_text(tex(best), encoding="utf-8")
    for p in [*paths, *p3, OUT_TEX]:
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
