"""Render the three v005 main-text figures from the CSVs of scripts/analyze_v005.py and the raw run records.

    uv run python scripts/render_v005_figures.py results/runs/c674c91e

Writes into figures/ (PDF for the paper, PNG for viewing) and chapters/results/_generated_figures.tex:
  rank__p3net__by_budget.pdf            relative rank of P3Net's median among the main-track arms, per space and budget
  quality_vs_cost__colorectal.pdf       median HV vs median optimiser time per arm, JAHS-Bench-201 CRC, b = 100 and 350
  fronts__colorectal__budget350.pdf     final non-dominated fronts of the median runs of P3Net, the best arm and random
                                        search, JAHS-Bench-201 CRC, b = 350
Palette: categorical slots 1-5 of the dataviz reference palette, validated with scripts/validate_palette.js (light
mode; contrast WARN for slots 3-5, relieved by markers, line styles and direct labels).
"""

