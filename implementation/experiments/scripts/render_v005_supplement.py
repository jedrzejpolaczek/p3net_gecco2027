def table(env, caption, label, cols, head, body):
    return rt.table(env, caption, label, cols, head, body)


def esc(s: str) -> str:
    return s.replace("%", "\\%").replace("#", "\\#")


# ------------------------------------------------------------------------------------------- medians, ranks

def cell_medians(per_run: pd.DataFrame) -> pd.DataFrame:
    med = per_run.groupby(["space", "budget", "method"]).value.median().reset_index()
    out = []
    for (s, b), c in med.groupby(["space", "budget"]):
        c = c[c.method.isin(MAIN_ARMS)].copy()
        asc = spec.SPACES[s][1] == "igd"
        c["rank"] = c.value.rank(ascending=asc, method="min").astype(int)
        c["n_arms"] = len(c)
        out.append(c)
    return pd.concat(out)


# ------------------------------------------------------------------------------------------- §5.2

def cost_to_target(ct: pd.DataFrame) -> str:
    c = ct[(ct.budget == BMAX) & ct.space.isin(PRIMARY)].copy()
    c["x"] = c.evaluations.fillna(c.cost)
    arms = [*MAIN_ARMS, *MF_ARMS]
    arms = [a for a in arms if a in set(c.method)]
    body = []
    for i, m in enumerate(arms):
        if i in (1, 5, 5 + len(spec.Q1)):
            body.append("\\midrule")
        cells = []
        for s in PRIMARY:
            for t in spec.TARGETS:
                r = c[(c.method == m) & (c.space == s) & (c.target == t)]
                rate = r.reached.mean()
                if not len(r) or rate == 0:
                    cells.append("--")
                    continue
                x = r[r.reached].x.median()
                cells.append(f"{x:.0f}" + ("" if rate == 1 else f"\\,({100 * rate:.0f})"))
        body.append(f"{NAMES[m]} & " + " & ".join(cells) + " \\\\")
    nt = len(spec.TARGETS)
    head = ["& " + " & ".join(f"\\multicolumn{{{nt}}}{{c}}{{{SHORT[s]}}}" for s in PRIMARY) + " \\\\",
            "".join(f"\\cmidrule(lr){{{2 + nt * i}-{1 + nt * (i + 1)}}}" for i in range(len(PRIMARY))),
            "\\textbf{Arm} & " + " & ".join(f"{int(100 * t)}\\,\\%" for _ in PRIMARY for t in spec.TARGETS) + " \\\\",
            "\\midrule"]
    cap = ("Cost to target (pre-registration \\S5.2), $b = 350$: median number of full evaluations (MF arms: cost in "
           "full-evaluation equivalents) after which a run first reaches 90, 95 or 99\\,\\% of the best median final "
           "quality in the cell (HV: $q \\cdot$ best; IGD+: best$/q$), over the runs that reach it; in brackets the "
           "percentage of the 30 runs that do, when below 100; -- = no run does. Simulated training time to target is "
           "in the released \\texttt{cost\\_to\\_target.csv}.")
    return "\n".join(table("table*", cap, "tab:v005-s-ctt", "l" + "r" * nt * len(PRIMARY), head, body))


# ------------------------------------------------------------------------------------------- §5.7

def budget_use(per_run: pd.DataFrame) -> str:
    pr = per_run[per_run.method.isin([*MAIN_ARMS, *MF_ARMS, *spec.GP])]
    rows = []
    for m, c in pr.groupby("method"):
        # no stop_reason in the record = the method's normal end, i.e. the budget was exhausted
        other = c[c.stop_reason.notna() & (c.stop_reason != "budget exhausted")]
        if not len(other):
            continue
        reasons = "; ".join(sorted(set(other.stop_reason)))
        rows.append((m, len(c), 100 * (1 - len(other) / len(c)), esc(reasons)))
    order = {m: i for i, m in enumerate([*MAIN_ARMS, *sorted(spec.GP), *MF_ARMS])}
    rows.sort(key=lambda r: order.get(r[0], 99))
    body = [f"{NAMES[m]} & {n:,} & {p:.1f} & {r} \\\\".replace(",", "\\,", 1) for m, n, p, r in rows]
    n_all = pr.method.nunique()
    cap = ("Budget use (pre-registration \\S5.7), all spaces and budgets: arms whose runs do not all end by exhausting "
           f"the budget ({len(rows)} of {n_all}; every other arm exhausts it in every run). The share of re-proposed "
           "solutions recorded in the run records is 0 for every run, because duplicates are filtered before "
           "evaluation and cost no budget (decision \\#35); re-proposal shows only as the stop reasons below.")
    head = ["\\textbf{Arm} & \\textbf{Runs} & \\textbf{Runs exhausting the budget, \\%} & \\textbf{Other stop reason} \\\\",
            "\\midrule"]
    return "\n".join(table("table*", cap, "tab:v005-s-budget", "lrrp{0.55\\textwidth}", head, body))


# ------------------------------------------------------------------------------------------- §5.6a

def hv_sensitivity(hs: pd.DataFrame) -> str:
    body = []
    for s in [x for x in PRIMARY if x in spec.JAHS_SPACES]:
        for b in spec.BUDGETS:
            c = hs[(hs.space == s) & (hs.budget == b)]
            p = c[c.method == spec.REF].iloc[0]
            body.append(f"{SHORT[s]} & {b} & {c['spearman_hv_1.05'].iloc[0]:.3f} & {c['spearman_hv_1.2'].iloc[0]:.3f} & "
                        f"{p['rank_hv_1.05']:g} & {p['rank_hv_1.1']:g} & {p['rank_hv_1.2']:g} & {len(c)} \\\\")
    cap = ("HV sensitivity to the reference point (pre-registration \\S5.6a), JAHS-Bench-201: Spearman correlation "
           "of the order of arms by median HV at reference points $(1.05, 1.05)$ and $(1.2, 1.2)$ with the order at "
           "the primary $(1.1, 1.1)$, and P3Net's rank at each (ties share the lower rank). Medians per arm and cell "
           "are in the released \\texttt{hv\\_sensitivity.csv}.")
    head = ["\\textbf{Space} & \\textbf{$b$} & $\\rho_{1.05}$ & $\\rho_{1.2}$ & \\multicolumn{3}{c}{P3Net rank at "
            "1.05 / 1.1 / 1.2} & \\textbf{Arms} \\\\", "\\midrule"]
    return "\n".join(table("table*", cap, "tab:v005-s-hvsens", "lrrrrrrr", head, body))


# ------------------------------------------------------------------------------------------- §5.9, §5.10

def unit_note() -> str:
    return ("Units of $f_1$: percentage points of validation error (JAHS-Bench-201, NAS-HPO-Bench-II, NAS-Bench-201) "
            "and validation MSE $\\times 10^{3}$ (FCNet).")


def per_space_table(rg: pd.DataFrame, col: str, label: str, cap: str) -> str:
    c = rg[rg.budget == BMAX]
    med = c.groupby(["method", "space"])[col].median()
    arms = [a for a in [*MAIN_ARMS, *MF_ARMS] if a in set(c.method)]
    body = []
    for i, m in enumerate(arms):
        if i in (1, 5, 5 + len(spec.Q1)):
            body.append("\\midrule")
        vals = []
        for s in ALL_SPACES:
            v = med.get((m, s), np.nan)
            if pd.isna(v):
                vals.append("--")
                continue
            vals.append(f"{1e3 * v:+.2f}" if s in FCNET and col == "front_gap" else
                        f"{1e3 * v:.2f}" if s in FCNET else f"{v:+.2f}" if col == "front_gap" else f"{v:.2f}")
        body.append(f"{NAMES[m]} & " + " & ".join(vals) + " \\\\")
    head = ["\\textbf{Arm} & " + " & ".join(f"\\textbf{{{SHORT[s]}}}" for s in ALL_SPACES) + " \\\\", "\\midrule"]
    return "\n".join(table("table*", cap + " " + unit_note(), label, "l" + "r" * len(ALL_SPACES), head, body))


# ------------------------------------------------------------------------------------------- NB201, Q7, GP

def nb201(med: pd.DataFrame) -> str:
    c = med[med.space == "nas_bench_201_v005"]
    arms = [a for a in MAIN_ARMS if a in set(c.method)]
    body = []
    for i, m in enumerate(arms):
        if i in (1, 5, 5 + len(spec.Q1)):
            body.append("\\midrule")
        cells = []
        for b in spec.BUDGETS:
            r = c[(c.method == m) & (c.budget == b)]
            cells.append("--" if not len(r) else f"{r.value.iloc[0]:.4f}\\,({r['rank'].iloc[0]})")
        body.append(f"{NAMES[m]} & " + " & ".join(cells) + " \\\\")
    n = {b: int(c[c.budget == b].n_arms.iloc[0]) for b in spec.BUDGETS}
    cap = ("NAS-Bench-201 (descriptive; $f_2$ = edge-GPU energy from HW-NAS-Bench): median normalised IGD+ over 30 "
           "seeds (lower is better) and, in brackets, the arm's rank in the cell (" +
           ", ".join(f"{n[b]} arms at $b = {b}$" for b in spec.BUDGETS) + "; ties share the lower rank).")
    head = ["\\textbf{Arm} & " + " & ".join(f"\\textbf{{{b}}}" for b in spec.BUDGETS) + " \\\\", "\\midrule"]
    return "\n".join(table("table*", cap, "tab:v005-s-nb201", "l" + "r" * len(spec.BUDGETS), head, body))


def q7(q7df: pd.DataFrame) -> str:
    body = []
    for s in ALL_SPACES:
        cells = []
        for b in spec.BUDGETS:
            r = q7df[(q7df.space == s) & (q7df.budget == b)]
            cells.append("--" if not len(r) else rt.cell(type("R", (), {"delta": r.delta.iloc[0],
                                                                         "significant": False})()))
        body.append(f"{SHORT[s]} & " + " & ".join(cells) + " \\\\")
    worse = int((q7df.delta < 0).sum())
    cap = ("Q7 (descriptive, no test): Cliff's $\\delta$ of P3-eLyMPuS vs.\\ canonical P3, 30 seeds each; negative "
           f"(red) favours canonical P3. P3-eLyMPuS is behind in {worse} of {len(q7df)} cells.")
    head = ["\\textbf{Space} & " + " & ".join(f"\\textbf{{{b}}}" for b in spec.BUDGETS) + " \\\\", "\\midrule"]
    return "\n".join(table("table*", cap, "tab:v005-s-q7", "l" + "c" * len(spec.BUDGETS), head, body))


def gp(med: pd.DataFrame) -> str:
    arms = [spec.REF, "v005_vizier", "v005_qnehvi", "v005_qparego"]
    gp_budgets = sorted(med[med.method.isin(spec.GP)].budget.unique())
    body = []
    for s in ALL_SPACES:
        for b in gp_budgets:
            c = med[(med.space == s) & (med.budget == b)]
            cells = []
            for m in arms:
                r = c[c.method == m]
                cells.append("--" if not len(r) else f"{r.value.iloc[0]:.4f}\\,({r['rank'].iloc[0]})")
            body.append(f"{SHORT[s]} & {b} & " + " & ".join(cells) + f" & {int(c.n_arms.iloc[0])} \\\\")
    cap = ("GP-based arms, run only at $b \\le 100$ (decision \\#30): median primary metric over 30 seeds (HV on "
           "JAHS-Bench-201, higher is better; normalised IGD+ elsewhere, lower is better) and, in brackets, the rank "
           "among all main-track arms run in the cell (Arms; ties share the lower rank). P3Net for reference.")
    head = ["\\textbf{Space} & \\textbf{$b$} & " + " & ".join(f"\\textbf{{{NAMES[m]}}}" for m in arms)
            + " & \\textbf{Arms} \\\\", "\\midrule"]
    return "\n".join(table("table*", cap, "tab:v005-s-gp", "lr" + "r" * len(arms) + "r", head, body))


# ------------------------------------------------------------------------------------------- §5.1 figure

#: categorical slots 1-3 of the reference palette (validated: scripts/validate_palette.js, light mode)
HIGHLIGHT = {spec.REF: ("#2a78d6", "-"), "v005_p3_canonical": ("#eb6834", "--"),
             "v005_random_search": ("#1baf7a", ":")}


def anytime_figure(at: pd.DataFrame, med: pd.DataFrame) -> list[Path]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from matplotlib.lines import Line2D

    fig, axes = plt.subplots(1, len(PRIMARY), figsize=(7.0, 2.3), constrained_layout=True)
    for ax, s in zip(axes, PRIMARY):
        c = at[(at.space == s) & (at.budget == BMAX) & (at.axis == "evaluations") & at.method.isin(MAIN_ARMS)]
        hv = spec.SPACES[s][1] == "hv"
        fin = med[(med.space == s) & (med.budget == BMAX)]
        best = fin.sort_values("value", ascending=not hv).method.iloc[0]
        for m, d in c.groupby("method"):
            if m in HIGHLIGHT or m == best:
                continue
            ax.plot(d.x, d["median"], color="#c3c2b7", lw=0.6, zorder=1)
        for m in [best, *HIGHLIGHT]:
            d = c[c.method == m]
            col, ls = HIGHLIGHT.get(m, ("#2f2f2d", "-."))
            ax.plot(d.x, d["median"], color=col, ls=ls, lw=1.4, zorder=3)
        vals = c[c.x >= 20]["median"]
        lo, hi = vals.quantile(0.02), vals.quantile(0.98)
        pad = 0.05 * (hi - lo)
        ax.set_ylim(lo - pad, hi + pad)
        ax.set_xlim(0, BMAX)
        ax.set_title(f"{SHORT[s]} (best: {NAMES[best]})", fontsize=7)
        ax.set_xlabel("full evaluations", fontsize=7)
        ax.set_ylabel("median HV" if hv else "median IGD+", fontsize=7)
        ax.tick_params(labelsize=6)
        ax.grid(alpha=0.25, lw=0.4)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    handles = [Line2D([], [], color=col, ls=ls, lw=1.4, label=NAMES[m]) for m, (col, ls) in HIGHLIGHT.items()]
    handles += [Line2D([], [], color="#2f2f2d", ls="-.", lw=1.4, label="best final arm (in title)"),
                Line2D([], [], color="#c3c2b7", lw=0.6, label="other arms")]
    fig.legend(handles=handles, loc="outside upper center", ncol=len(handles), fontsize=6, frameon=False)
    OUT_FIG.mkdir(parents=True, exist_ok=True)
    paths = [OUT_FIG / "anytime__primary__budget350.pdf", OUT_FIG / "anytime__primary__budget350.png"]
    for p in paths:
        fig.savefig(p, dpi=200)
    plt.close(fig)
    return paths


def anytime_tex() -> str:
    return "\n".join([
        "\\begin{figure*}[t]", "    \\centering",
        "    \\includegraphics[width=\\textwidth]{figures/anytime__primary__budget350.pdf}",
        "    \\caption{Anytime quality (pre-registration \\S5.1), primary spaces, $b = 350$: median over 30 seeds of "
        "the primary metric after each full evaluation (HV higher is better, IGD+ lower is better; y-axis cut to the "
        "range after 20 evaluations). Grey: all other main-track arms; dash-dot: the arm with the best median final "
        "value in the space. Multi-fidelity arms are on a cost axis and are in the released "
        "\\texttt{anytime.csv}.}",
        "    \\Description{Four line charts, one per primary search space, of median quality against the number of "
        "full evaluations up to 350, highlighting P3Net, canonical P3, random search and the best arm.}",
        "    \\label{fig:v005-s-anytime}", "\\end{figure*}", ""])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("analysis", type=Path)
    args = ap.parse_args(argv)
    a = args.analysis
    per_run = pd.read_csv(a / "per_run.csv", usecols=["method", "space", "budget", "seed", "value", "stop_reason"])
    med = cell_medians(per_run)
    rg = pd.read_csv(a / "regret_generalisation.csv")
    parts = [
        cost_to_target(pd.read_csv(a / "cost_to_target.csv")),
        budget_use(per_run),
        hv_sensitivity(pd.read_csv(a / "hv_sensitivity.csv")),
        per_space_table(rg, "regret", "tab:v005-s-regret",
                        "Simple regret of $f_1$ (pre-registration \\S5.10), $b = 350$: median over 30 seeds of the "
                        "best $f_1$ found minus the best $f_1$ of the oracle front (tabular spaces) or the best $f_1$ "
                        "found by any run in the cell (JAHS-Bench-201)."),
        per_space_table(rg, "front_gap", "tab:v005-s-gap",
                        "Generalisation gap (pre-registration \\S5.9), $b = 350$: median over 30 seeds of the mean "
                        "(test $-$ validation) $f_1$ of the members of the run's final non-dominated set; the methods "
                        "never see test values. Positive: worse on test."),
        nb201(med), q7(pd.read_csv(a / "q7_elympus.csv")), gp(med), anytime_tex(),
    ]
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text("\n".join(HEADER) + "\n\n".join(parts), encoding="utf-8")
    print(OUT_TEX)
    for p in anytime_figure(pd.read_csv(a / "anytime.csv"), med):
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
