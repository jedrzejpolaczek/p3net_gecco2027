"""
Render every data-bearing LaTeX table in the Results section from the
generated markdown tables.

Audit finding R1 (second half): the effect-size heatmaps and fixed-budget
tables in chapters/v003/results/main.tex were produced by hand, with the
colour of every cell chosen per cell. They were correct when written, but
nothing tied them to the data -- so when the headline metric for
NAS-HPO-Bench-II moved from hypervolume-relative to IGD+, every one of
those cells would have silently kept showing the old numbers.

Writes, into chapters/v003/results/:

* _generated_heatmaps.tex         -- one effect-size heatmap per search space
* _generated_fixed_budget.tex     -- one median/IQR/p/delta table per search space
                                     (supplementary material; too long for 8 pages)
* _generated_summary.tex          -- the narrative paragraphs
                                     (scripts/render_results_narrative.py)

Every generated file carries a do-not-edit header. Regenerate after every
reporting pass:

    python scripts/generate_report.py
    python scripts/render_results_tex.py
    python scripts/check_paper_numbers.py --strict
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

EXPERIMENTS_ROOT = Path(__file__).resolve().parent.parent
REPO_ROOT = EXPERIMENTS_ROOT.parents[1]
if str(EXPERIMENTS_ROOT) not in sys.path:
    sys.path.insert(0, str(EXPERIMENTS_ROOT))

from scripts.render_results_narrative import (  # noqa: E402
    DISPLAY_NAMES,
    SPACE_NAMES,
    Row,
    read_table,
    render_ablation_family_paragraph,
    render_external_trend_paragraph,
    render_fixed_budget_paragraph,
    render_ranking_paragraph,
)

TABLES_DIR = EXPERIMENTS_ROOT / "results" / "tables"
OUT_DIR = REPO_ROOT / "chapters" / "v003" / "results"

SPACE_ORDER = ["jahs_bench_201", "jahs_bench_201_colorectal", "jahs_bench_201_fashion", "nas_hpo_bench_ii"]
SPACE_LABELS = {
    "jahs_bench_201": "jahs",
    "jahs_bench_201_colorectal": "colorectal",
    "jahs_bench_201_fashion": "fashion",
    "nas_hpo_bench_ii": "nashpo",
}

#: Heatmap row order: arms sharing P3Net's engine, then NSGA-II-engine
#: arms, then external baselines -- grouped so the reader can scan for the
#: engine-level pattern the Diagnostics paragraphs discuss.
HEATMAP_GROUPS = [
    ["p3_alone", "p3_alone_pop20", "p3_alone_pop40", "p3_absolute"],
    ["nsga_net", "nsganetv2"],
    ["mo_bohb", "random_search", "sh_emoa", "tpe"],
]

HEADER = [
    "% GENERATED by implementation/experiments/scripts/render_results_tex.py.",
    "% Do not edit by hand -- regenerate from results/tables/ instead.",
    "",
]

METRIC_NAMES = {
    "hypervolume_relative": "hypervolume relative to the frozen best-known front (higher is better)",
    "igd_plus": "normalised IGD+ against the exact oracle front (lower is better)",
}


def _cell_colour(effect: float) -> tuple[str, str]:
    """(background hex, text colour). Blue favours P3Net, red favours the
    baseline; five magnitude bands. Thresholds reproduce the palette the
    hand-made tables used, so regenerated tables look identical wherever
    the numbers did not change."""
    magnitude = abs(effect)
    if effect > 0:
        bands = [(0.1, "EAF2FC", "black"), (0.3, "CDE2FB", "black"), (0.5, "86B6EF", "black"), (0.7, "3987E5", "white")]
        top = ("184F95", "white")
    else:
        bands = [(0.1, "FDEEED", "black"), (0.3, "FBDCDB", "black"), (0.5, "F2A3A2", "black"), (0.7, "E34948", "white")]
        top = ("941F1F", "white")
    for limit, bg, fg in bands:
        if magnitude < limit:
            return bg, fg
    return top


def _heatmap_cell(row: Row | None) -> str:
    if row is None or row.effect is None:
        return "--"
    bg, fg = _cell_colour(row.effect)
    text = f"{row.effect:+.2f}"
    if row.reject:
        return (
            f"\\fcolorbox[HTML]{{000000}}{{{bg}}}"
            f"{{\\makebox[2.4em]{{\\textcolor{{{fg}}}{{\\textbf{{{text}}}}}}}}}"
        )
    return f"\\colorbox[HTML]{{{bg}}}{{\\makebox[2.4em]{{\\textcolor{{{fg}}}{{{text}}}}}}}"


def render_heatmaps(rows: list[Row]) -> str:
    index = {(r.method, r.search_space, r.budget): r for r in rows}
    budgets = sorted({r.budget for r in rows})
    out = list(HEADER)
    for space in SPACE_ORDER:
        space_rows = [r for r in rows if r.search_space == space]
        if not space_rows:
            continue
        metric = METRIC_NAMES.get(space_rows[0].metric, space_rows[0].metric)
        out += [
            "\\begin{table}[t]",
            "    \\centering",
            "    \\footnotesize",
            f"    \\caption{{Effect-size heatmap, {SPACE_NAMES[space]}: Cliff's $\\delta$ of P3Net vs.\\ each "
            f"baseline on {metric}. Blue favours P3Net, red favours the baseline; darker is larger "
            "$|\\delta|$. Boxed cells reject $H_0$ at $\\alpha=0.05$ (Holm--Bonferroni, per cell).}",
            f"    \\label{{tab:heatmap-{SPACE_LABELS[space]}}}",
            "    \\begin{tabular}{@{}l" + "c" * len(budgets) + "@{}}",
            "        \\toprule",
            "        \\textbf{Method} & " + " & ".join(f"\\textbf{{{b}}}" for b in budgets) + " \\\\",
        ]
        for g, group in enumerate(HEATMAP_GROUPS):
            out.append("        \\midrule")
            for method in group:
                cells = [_heatmap_cell(index.get((method, space, b))) for b in budgets]
                out.append(f"        {DISPLAY_NAMES[method]} & " + " & ".join(cells) + " \\\\")
        out += ["        \\bottomrule", "    \\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def render_fixed_budget_tables(rows: list[Row]) -> str:
    out = list(HEADER)
    budgets = sorted({r.budget for r in rows})
    for space in SPACE_ORDER:
        space_rows = [r for r in rows if r.search_space == space]
        if not space_rows:
            continue
        metric_key = space_rows[0].metric
        metric = METRIC_NAMES.get(metric_key, metric_key)
        precision = 4
        out += [
            "\\begin{table}[t]",
            "    \\centering",
            "    \\footnotesize",
            f"    \\caption{{Fixed-budget summary, {SPACE_NAMES[space]}: median and IQR of {metric}; "
            "Holm--Bonferroni-corrected Wilcoxon $p$ and Cliff's $\\delta$ of each method vs.\\ P3Net, "
            "corrected per (search space, budget) cell. $n=30$ seeds per row; $^{*}$ rejects $H_0$ at "
            "$\\alpha=0.05$. Positive $\\delta$ favours P3Net.}",
            f"    \\label{{tab:fixed-budget-{SPACE_LABELS[space]}}}",
            "    \\begin{tabular}{@{}lrrrr@{}}",
            "        \\toprule",
            "        \\textbf{Method} & \\textbf{Median} & \\textbf{IQR} & \\textbf{Adj.\\ $p$} & "
            "\\textbf{Cliff's $\\delta$} \\\\",
        ]
        for b in budgets:
            out += ["        \\midrule", f"        \\multicolumn{{5}}{{l}}{{\\emph{{Budget = {b}}}}} \\\\"]
            for r in sorted((x for x in space_rows if x.budget == b), key=lambda x: DISPLAY_NAMES[x.method]):
                name = DISPLAY_NAMES[r.method]
                if r.method == "p3net":
                    out.append(
                        f"        \\textbf{{{name} (ref.)}} & \\textbf{{{r.median:.{precision}f}}} & "
                        f"\\textbf{{{r.iqr:.{precision}f}}} & -- & -- \\\\"
                    )
                    continue
                p = f"{r.adj_p:.3f}"
                if r.reject:
                    p = f"\\textbf{{{p}$^{{*}}$}}"
                out.append(
                    f"        {name} & {r.median:.{precision}f} & {r.iqr:.{precision}f} & {p} & {r.effect:+.3f} \\\\"
                )
        out += ["        \\bottomrule", "    \\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def render_summary(rows: list[Row]) -> str:
    return "\n".join(
        HEADER
        + [
            render_fixed_budget_paragraph(rows),
            "",
            render_external_trend_paragraph(rows),
            "",
            render_ablation_family_paragraph(rows),
            "",
        ]
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables-dir", type=Path, default=TABLES_DIR)
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = parser.parse_args(argv)

    rows = read_table(args.tables_dir / "fixed_budget_summary.md")
    if not rows:
        raise SystemExit("no rows -- run scripts/generate_report.py first")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "_generated_heatmaps.tex": render_heatmaps(rows),
        "_generated_fixed_budget.tex": render_fixed_budget_tables(rows),
        "_generated_summary.tex": render_summary(rows),
    }
    for name, body in outputs.items():
        path = args.out_dir / name
        path.write_text(body, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
