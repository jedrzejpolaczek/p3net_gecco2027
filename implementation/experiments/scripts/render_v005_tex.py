"""Render the v005 result tables into chapters/results/ from the CSVs of scripts/analyze_v005.py.
The v003 chapters are not touched.

    uv run python scripts/render_v005_tex.py results/runs/c674c91e/analysis

Writes (each file starts with a do-not-edit header):
  _generated_q1_heatmaps.tex  Q1: Cliff's delta of P3Net vs each comparison arm, one table per primary space
  _generated_q2_q3.tex        Q2/Q3: delta, 90 % bootstrap CI, TOST verdict, share of runs identical to P3Net
  _generated_q4_mf.tex        Q4: delta of P3Net vs the multi-fidelity arms (primary spaces)
  _generated_q5_fcnet.tex     Q5: delta of P3Net vs the Q1 arms on the four FCNet tasks
  _generated_q6_costs.tex     Q6: optimiser wall-clock time and peak process memory per arm

Delta is oriented so that positive favours P3Net (pre-registration §4); boxed = rejected after Holm in
the cell's family. Needs the LaTeX packages booktabs and xcolor (with the `table` option not required).
"""

