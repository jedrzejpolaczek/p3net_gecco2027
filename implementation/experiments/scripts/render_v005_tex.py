DELTA_NOTE = ("Cliff's $\\delta$ of P3Net vs.\\ each arm, 30 seeds each; positive (blue) favours P3Net, negative (red) "
              "the arm; darker is larger $|\\delta|$. Boxed: rejects $H_0$ after Holm--Bonferroni within the (space, "
              "budget) cell, two-sided Mann--Whitney $U$, $\\alpha=0.05$.")


def colour(d: float) -> tuple[str, str]:
    """Same palette as scripts/render_results_tex.py (v003 tables)."""
    m = abs(d)
    if d > 0:
        bands, top = [(0.1, "EAF2FC", "black"), (0.3, "CDE2FB", "black"), (0.5, "86B6EF", "black"),
                      (0.7, "3987E5", "white")], ("184F95", "white")
    else:
        bands, top = [(0.1, "FDEEED", "black"), (0.3, "FBDCDB", "black"), (0.5, "F2A3A2", "black"),
                      (0.7, "E34948", "white")], ("941F1F", "white")
    return next(((bg, fg) for lim, bg, fg in bands if m < lim), top)


def cell(row) -> str:
    if row is None:
        return "--"
    bg, fg = colour(row.delta)
    text = f"{row.delta:+.2f}"
    if row.significant:
        return f"\\fcolorbox[HTML]{{000000}}{{{bg}}}{{\\makebox[2.2em]{{\\textcolor{{{fg}}}{{\\textbf{{{text}}}}}}}}}"
    return f"\\colorbox[HTML]{{{bg}}}{{\\makebox[2.2em]{{\\textcolor{{{fg}}}{{{text}}}}}}}"


def index(q: pd.DataFrame, family: str) -> dict:
    return {(r.arm, r.space, int(r.budget)): r for r in q[q.family == family].itertuples()}


def table(env: str, caption: str, label: str, cols: str, head: list[str], body: list[str]) -> list[str]:
    return [f"\\begin{{{env}}}[t]", "    \\centering", "    \\footnotesize", "    \\setlength{\\tabcolsep}{2pt}",
            f"    \\caption{{{caption}}}", f"    \\label{{{label}}}", f"    \\begin{{tabular}}{{@{{}}{cols}@{{}}}}",
            "        \\toprule", *[f"        {h}" for h in head], *[f"        {b}" for b in body],
            "        \\bottomrule", "    \\end{tabular}", f"\\end{{{env}}}", ""]


# ------------------------------------------------------------------------------------------------ Q1

def q1(q: pd.DataFrame) -> str:
    idx = index(q, "Q1")
    out = list(HEADER)
    for s in PRIMARY:
        body = []
        for g, group in enumerate(Q1_GROUPS):
            if g:
                body.append("\\midrule")
            body += [f"{NAMES[m]} & " + " & ".join(cell(idx.get((m, s, b))) for b in spec.BUDGETS) + " \\\\"
                     for m in group]
        cap = (f"Q1, {SPACES[s][0]}: {DELTA_NOTE} Metric: {METRIC[spec.SPACES[s][1]]}. Holm family: 17 arms at "
               "budgets 50 and 100, 14 at 200 and 350 (OSS Vizier, qNEHVI and qParEGO run only at 50 and 100; "
               "-- = not run).")
        out += table("table", cap, f"tab:v005-q1-{SPACES[s][1]}", "l" + "c" * len(spec.BUDGETS),
                     ["\\textbf{Arm} & " + " & ".join(f"\\textbf{{{b}}}" for b in spec.BUDGETS) + " \\\\",
                      "\\midrule"], body)
    return "\n".join(out)


# ------------------------------------------------------------------------------------------------ Q2/Q3

def identical_share(per_run: pd.DataFrame, arm: str, space: str, budget: int) -> float:
    a = per_run[(per_run.method == spec.REF) & (per_run.space == space) & (per_run.budget == budget)]
    b = per_run[(per_run.method == arm) & (per_run.space == space) & (per_run.budget == budget)]
    m = a.merge(b, on="seed", suffixes=("_ref", "_arm"))
    return float((m.value_ref == m.value_arm).mean()) if len(m) else float("nan")


def q2_q3(q: pd.DataFrame, tost: pd.DataFrame, per_run: pd.DataFrame) -> str:
    sig = index(q, "Q2")
    pairs = [(a, f"v005_p3net vs {a}") for a in spec.Q2]
    body = []
    for s in PRIMARY:
        body.append("\\midrule")
        for b in spec.BUDGETS:
            cells = []
            for arm, pair in pairs:
                t = tost[(tost.pair == pair) & (tost.space == s) & (tost.budget == b)].iloc[0]
                star = "^{*}" if sig[(arm, s, b)].significant else ""
                verdict = {"equivalent": "eq.", "inconclusive": "inc.", "different": "diff."}[t["verdict_0.33"]]
                cells += [f"${t.delta:+.2f}{star}$", f"$[{t.ci_lo:+.2f}, {t.ci_hi:+.2f}]$", verdict,
                          f"{100 * identical_share(per_run, arm, s, b):.0f}"]
            body.append(f"{SHORT[s]} & {b} & " + " & ".join(cells) + " \\\\")
    n_sig = sum(int(r.significant) for r in sig.values())
    ref = per_run[(per_run.method == spec.REF) & per_run.space.isin(PRIMARY)]
    steps = ref.groupby("budget").mixing_steps.median()
    steps_text = ", ".join(f"{steps.get(b, float('nan')):.0f}" for b in spec.BUDGETS)
    budgets_text = ", ".join(map(str, spec.BUDGETS))
    head = ["& & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{P3Net vs.\\ {NAMES[a]}}}" for a, _ in pairs) + " \\\\",
            "".join(f"\\cmidrule(lr){{{3 + 4 * i}-{6 + 4 * i}}}" for i in range(3)),
            "\\textbf{Space} & \\textbf{$b$} & " + " & ".join(["$\\delta$ & 90\\,\\% CI & TOST & same\\,\\%"] * 3)
            + " \\\\"]
    m_main, m_side = spec.TOST_MARGINS
    side = tost[f"verdict_{m_side}"].value_counts().to_dict()
    side_text = ", ".join(f"{v} {k}" for k, v in sorted(side.items()))
    cap = ("Q2 and Q3, what the surrogate contributes: Cliff's $\\delta$ (positive favours P3Net; $^{*}$ = rejected "
           f"after Holm within the cell's Q2 family; {n_sig} of {len(sig)} comparisons are), its 90\\,\\% percentile "
           f"bootstrap CI ({spec.TOST_RESAMPLES:,} resamples) and the TOST verdict at margin $m={m_main}$ (eq.\\ = CI "
           f"within $(-m, m)$; diff.\\ = CI excludes 0; inc.\\ = neither; at $m={m_side}$: {side_text} of "
           f"{len(tost)}). same\\,\\% = share of the 30 seeds whose final metric value is identical to P3Net's. "
           f"Median number of P3Net mixing steps per run over these spaces at $b = {budgets_text}$: {steps_text}.")
    cap = cap.replace(f"{spec.TOST_RESAMPLES:,}", f"{spec.TOST_RESAMPLES:,}".replace(",", "\\,"))
    return "\n".join(HEADER + table("table*", cap, "tab:v005-q2-q3", "lr" + "rrrr" * 3, head, body))


# ------------------------------------------------------------------------------------------------ Q4, Q5

def wide_heatmap(q: pd.DataFrame, family: str, arms: list[str], spaces: list[str], caption: str, label: str) -> str:
    idx = index(q, family)
    nb = len(spec.BUDGETS)
    head = ["& " + " & ".join(f"\\multicolumn{{{nb}}}{{c}}{{{SHORT[s]}}}" for s in spaces) + " \\\\",
            "".join(f"\\cmidrule(lr){{{2 + nb * i}-{1 + nb * (i + 1)}}}" for i in range(len(spaces))),
            "\\textbf{Arm} & " + " & ".join(f"{b}" for _ in spaces for b in spec.BUDGETS) + " \\\\", "\\midrule"]
    body = [f"{NAMES[m]} & " + " & ".join(cell(idx.get((m, s, b))) for s in spaces for b in spec.BUDGETS) + " \\\\"
            for m in arms]
    return "\n".join(HEADER + table("table*", caption, label, "l" + "c" * nb * len(spaces), head, body))


def q4(q: pd.DataFrame) -> str:
    cap = (f"Q4, multi-fidelity track, primary spaces: {DELTA_NOTE} Holm family: the five MF arms. Equal cost in "
           "full-evaluation equivalents; each MF arm's result is the set of configurations it trained to full "
           "length. Columns: budget per space (C10, CRC, FMN: JAHS-Bench-201 tasks; NHB: NAS-HPO-Bench-II).")
    return wide_heatmap(q, "Q4", list(spec.Q4), PRIMARY, cap, "tab:v005-q4-mf")


def q5(q: pd.DataFrame) -> str:
    rows = [m for g in Q1_GROUPS for m in g]
    cap = (f"Q5, FCNet (four tasks, normalised IGD+): {DELTA_NOTE} Holm family as in Q1 (17 arms at budgets 50 and "
           "100, 14 at 200 and 350; -- = not run). Columns: budget per task.")
    return wide_heatmap(q, "Q5", rows, FCNET, cap, "tab:v005-q5-fcnet")


# ------------------------------------------------------------------------------------------------ Q6

def fmt_seconds(x: float) -> str:
    if pd.isna(x):
        return "--"
    return f"{x:.1f}" if x < 100 else f"{x:,.0f}".replace(",", "\\,")


def q6(costs: pd.DataFrame) -> str:
    arms = [spec.REF, *spec.Q2, "v005_p3_elympus", *[m for g in Q1_GROUPS for m in g], *spec.Q4]
    body = []
    for i, m in enumerate(arms):
        if i in (1, 5, 5 + len(spec.Q1)):
            body.append("\\midrule")
        b = 100 if m in spec.GP else max(spec.BUDGETS)
        c = costs[(costs.method == m) & (costs.budget == b)].set_index("space")
        times = [fmt_seconds(c.method_wall_seconds.get(s, float("nan"))) for s in PRIMARY]
        mem = c.peak_memory_process_mb.reindex(PRIMARY).median()
        body.append(f"{NAMES[m]} & {b} & " + " & ".join(times) + f" & {mem / 1024:.1f} \\\\")
    head = ["\\textbf{Arm} & \\textbf{$b$} & " + " & ".join(
        f"\\textbf{{{SHORT[s]}}}" + ("$^{\\dagger}$" if s == "jahs_bench_201_v005" else "") for s in PRIMARY)
            + " & \\textbf{GB} \\\\", "\\midrule"]
    cap = ("Q6, practical cost at each arm's largest budget ($b$; the GP arms ran only up to 100): median optimiser "
           "wall-clock time in seconds without benchmark queries, per primary space, and the median over these spaces "
           "of the median per-run peak process memory (GB). Times measured with 6 workers sharing 16 vCPUs; OSS "
           "Vizier alone on the machine. $^{\\dagger}$JAHS-Bench-201 CIFAR-10: every point except OSS Vizier was "
           "rerun with 2 workers after the shared benchmark process was stopped by the out-of-memory killer "
           "(pre-registration \\S8), so these times are not directly comparable with the other columns.")
    return "\n".join(HEADER + table("table", cap, "tab:v005-q6-costs", "lr" + "r" * len(PRIMARY) + "r", head, body))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("analysis", type=Path, help="results/runs/<root>/analysis")
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    args = ap.parse_args(argv)
    a = args.analysis
    q = pd.read_csv(a / "q_tests.csv")
    tost = pd.read_csv(a / "q3_tost.csv")
    per_run = pd.read_csv(a / "per_run.csv", usecols=["method", "space", "budget", "seed", "value", "mixing_steps"])
    costs = pd.read_csv(a / "costs.csv")
    args.out.mkdir(parents=True, exist_ok=True)
    files = {"_generated_q1_heatmaps.tex": q1(q), "_generated_q2_q3.tex": q2_q3(q, tost, per_run),
             "_generated_q4_mf.tex": q4(q), "_generated_q5_fcnet.tex": q5(q), "_generated_q6_costs.tex": q6(costs)}
    for name, text in files.items():
        (args.out / name).write_text(text, encoding="utf-8")
        print(f"{args.out / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
